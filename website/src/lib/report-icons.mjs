/** The icon of a product, or undefined when it has none (the page shows its initials instead). */
export const productIcon = (product) => (PRODUCT_ICONS[product] ? `${base}/products/${PRODUCT_ICONS[product]}` : undefined);

/** The icon of a product's feature, or undefined when it has none. */
export const featureIcon = (product, feature) => {
	const file = FEATURE_ICONS[`${product}/${feature}`];
	return file ? `${base}/features/${file}.svg` : undefined;
};

/** Two letters for a product without an icon. */
export const productInitials = (product) => ({ ad: 'AD', github: 'GH', fabric: 'Fb' })[product] ?? product.slice(0, 2).toUpperCase();
