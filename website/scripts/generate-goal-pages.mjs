// Writes one page per goal of the defender's path to website/docs/defenders-path/<goal>.md, which git ignores, from
// the step catalogue (powershell/assets/steps), the measure registry and the test catalog
// (src/data/test-catalog.json, for the tests whose Step names each step). scripts/prepare-data.mjs runs it before
// every dev server and build. The concept page, docs/defenders-path/readme.mdx, is kept in git and links the goals.
//   node scripts/generate-goal-pages.mjs
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { goalPath, loadStepCatalog, stepAnchor, stepUrl } from "./step-catalog.mjs";

const websiteRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputRoot = join(websiteRoot, "docs", "defenders-path");
const catalogPath = join(websiteRoot, "src", "data", "test-catalog.json");
const marker = "<!-- This file is generated by website/scripts/generate-goal-pages.mjs from powershell/assets/steps. Do not edit it. -->";
const editUrl = "https://github.com/maester365/maester/edit/main/powershell/assets/steps/goals.json";

const conditionText = (key) => {
  if (key === "hybrid-identity") return "the tenant syncs identities from on-premises (hybrid identity)";
  if (key.startsWith("license:")) return `the tenant has the ${key.slice("license:".length).split("&").map((p) => `\`${p}\``).join(" and ")} service plan`;
  return `\`${key}\``;
};
const text = (value) => String(value ?? "").replace(/</g, "&lt;");
const list = (items, last = "and") => (items.length < 2 ? items.join("") : `${items.slice(0, -1).join(", ")} ${last} ${items.at(-1)}`);

function loadTests() {
  if (!existsSync(catalogPath)) return { byStep: new Map(), products: new Map(), hasSteps: false };
  const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
  const byStep = new Map();
  let hasSteps = false;
  for (const test of catalog.Tests ?? []) {
    if (Object.hasOwn(test, "Step")) hasSteps = true;
    for (const step of test.Step ?? []) {
      if (!byStep.has(step)) byStep.set(step, []);
      byStep.get(step).push(test);
    }
  }
  for (const tests of byStep.values()) tests.sort((a, b) => a.Id.localeCompare(b.Id, undefined, { numeric: true }));
  const products = new Map((catalog.Taxonomy?.Products ?? []).map((p) => [p.Key, p.Name]));
  return { byStep, products, hasSteps };
}

function renderGoal(goal, index, catalog, tests) {
  const { steps, measures } = catalog;
  const inGoal = new Set(goal.Steps);
  const link = (id) => {
    const step = steps.get(id);
    if (!step) return `\`${id}\``;
    return `[${text(step.Title)}](${inGoal.has(id) ? `#${stepAnchor(id)}` : stepUrl(step)})`;
  };
  const final = steps.get(goal.Step);
  const verified = goal.Steps.filter((id) => (tests.byStep.get(id) ?? []).length > 0).length;
  const measured = goal.Steps.filter((id) => steps.get(id).Measure).length;
  const otherGoals = (step) => step.Goals.filter((g) => g !== goal.Id);

  const body = [marker, "", text(goal.Summary), ""];
  body.push(
    `The goal is reached when the last step, [${text(final.Title)}](#${stepAnchor(final.Id)}), is done. It has ${goal.Steps.length} steps, prerequisites first. ` +
      `Maester tests ${verified} of them and measures ${measured}. See [Defender's path](/docs/defenders-path) for what the statuses and relationships mean.`,
    "",
  );
  body.push("```powershell title=\"Check every step of this goal\"", `Invoke-Maester -Step ${goal.Step} -IncludePrerequisites`, "```", "");
  body.push("## Steps", "");
  body.push("| # | Step | Checked by |", "| --- | --- | --- |");
  goal.Steps.forEach((id, i) => {
    const step = steps.get(id);
    const ids = (tests.byStep.get(id) ?? []).map((t) => `[${t.Id}](/docs/tests/${t.Id})`);
    const how = [...ids, step.Measure ? `Measure \`${step.Measure.Key}\`` : ""].filter(Boolean).join(", ") || "Not checked yet";
    body.push(`| ${i + 1} | [${text(step.Title)}](#${stepAnchor(id)}) | ${how} |`);
  });
  body.push("");

  goal.Steps.forEach((id, i) => {
    const step = steps.get(id);
    body.push(`<a id="${stepAnchor(id)}"></a>`, "", `### ${i + 1}. ${text(step.Title)}`, "");
    body.push(`\`${step.Id}\` · ${text(tests.products.get(step.Product) ?? step.Product)}`, "");
    body.push(text(step.Summary), "");

    const facts = [];
    if (step.Requires.length) facts.push(`- **Requires:** ${list(step.Requires.map(link))}.`);
    for (const group of step.RequiresOneOf) facts.push(`- **Requires one of:** ${list(group.map(link), "or")}.`);
    if (step.RecommendedFirst.length) facts.push(`- **Recommended first:** ${list(step.RecommendedFirst.map(link))}.`);
    if (step.Conflicts.length) facts.push(`- **Must be off first:** ${list(step.Conflicts.map(link))}.`);
    if (step.OnlyWhen.length) facts.push(`- **Applies only when** ${list(step.OnlyWhen.map(conditionText))}.`);
    const unlocks = goal.Steps.filter((other) => {
      const o = steps.get(other);
      return o.Requires.includes(id) || o.RequiresOneOf.some((g) => g.includes(id)) || o.RecommendedFirst.includes(id);
    });
    if (unlocks.length) facts.push(`- **Comes before:** ${list(unlocks.map(link))}.`);
    const others = otherGoals(step);
    if (others.length) facts.push(`- **Also part of:** ${list(others.map((g) => `[${text(catalog.goals.find((x) => x.Id === g).Title)}](${goalPath(g)}#${stepAnchor(id)})`))}.`);
    if (facts.length) body.push(...facts, "");

    const verifying = tests.byStep.get(id) ?? [];
    if (verifying.length) {
      body.push("**Checked by**", "");
      for (const t of verifying) body.push(`- [${t.Id}](/docs/tests/${t.Id}): ${text(t.Title.replace(/\.$/, ""))}`);
      body.push("");
    }
    if (step.Measure) {
      const measure = measures.get(step.Measure.Key);
      body.push("**Measure**", "");
      body.push(
        `Maester reads \`${step.Measure.Key}\`${measure?.title ? ` (${text(measure.title)})` : ""} from Microsoft Graph whenever this step is in scope. ` +
          `The step is done when at least ${step.Measure.MinimumShare}% of ${text(measure?.unit || "objects")} meet the bar. ${measure?.caveat ? text(measure.caveat) : ""}`.trimEnd(),
        "",
      );
    }
    if (!verifying.length && !step.Measure) {
      body.push(`**Checked by:** ${text(step.Unchecked ?? "no Maester check names this step yet.")}`, "");
    }
    if (step.Rollout.length) {
      body.push("**How to switch it on**", "");
      step.Rollout.forEach((line, n) => body.push(`${n + 1}. ${text(line)}`));
      body.push("");
    }
    body.push("**Sources**", "");
    for (const source of step.Sources) {
      const where = source.Url ? `[Microsoft Learn](${source.Url})` : `maintainer ${text(source.Maintainer)}`;
      body.push(`- ${text(source.Note)} (${where}, reviewed ${source.Reviewed})`);
    }
    body.push("");
  });

  return `---
title: ${JSON.stringify(goal.Title)}
description: ${JSON.stringify(goal.Summary)}
editUrl: ${JSON.stringify(editUrl)}
sidebar:
  order: ${index + 2}
---

${body.join("\n")}`;
}

export function main() {
  const catalog = loadStepCatalog();
  const tests = loadTests();
  if (!tests.hasSteps) console.warn("generate-goal-pages: the test catalog has no Step values. Run `npm run refresh-data` to export it again.");
  mkdirSync(outputRoot, { recursive: true });
  for (const name of readdirSync(outputRoot)) if (name.endsWith(".md")) rmSync(join(outputRoot, name));
  catalog.goals.forEach((goal, index) => writeFileSync(join(outputRoot, `${goal.Id}.md`), `${renderGoal(goal, index, catalog, tests).trimEnd()}\n`));
  return catalog.goals.length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(`Generated ${main()} goal pages of the defender's path.`);
}
