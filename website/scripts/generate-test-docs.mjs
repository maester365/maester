function walkFiles(dir, predicate = () => true) {
  if (!existsSync(dir)) return [];
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walkFiles(path, predicate));
    else if (predicate(path)) files.push(path);
  }
  return files.sort();
}

function yamlQuote(value) {
  // The MDX loader writes frontmatter strings into JavaScript without escaping backslashes, so
  // "domain\username" becomes an invalid "\u" escape and fails the build. Doubling the backslash
  // would fix that but shows "\\" in the page metadata, which Docusaurus parses separately, so
  // swap in a look-alike (U+2216 SET MINUS) instead.
  return JSON.stringify(String(value ?? "").replaceAll("\\", "\u2216"));
}

// Source paths are embedded in generated docs and used as contributors.mjs
// lookup keys against git's always-forward-slash paths; node:path's relative()
// returns native separators, which would silently break both on Windows
// (backslashes never match, so every test's contributor attribution is empty).
function toPosixPath(value) {
  return sep === "/" ? value : value.split(sep).join("/");
}

function escapeTable(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("<br>", "<br />")
    .replaceAll("\n", "<br />");
}

function jsxText(value) {
  return String(value ?? "").replace(/[&<>{}]/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "{": "&#123;", "}": "&#125;" }[ch]));
}

function jsxAttr(value) {
  return jsxText(value).replaceAll('"', "&quot;");
}

function contributorLinkTarget(profile) {
  return profile ? `/contributors/${profile.id.toLowerCase()}` : "/contributors";
}

function renderBylineAvatar(profile, extraClass, roleLabel) {
  if (!profile) return "";
  const title = `${profile.name}${roleLabel ? ` · ${roleLabel}` : ""}`;
  const inner = profile.avatar
    ? `<img src="${jsxAttr(profile.avatar)}" alt="${jsxAttr(profile.name)}" />`
    : `<span className="test-byline-initials">${jsxText(profile.initials ?? "?")}</span>`;
  return `<a className="test-byline-avatar${extraClass}" href="${jsxAttr(contributorLinkTarget(profile))}" title="${jsxAttr(title)}">${inner}</a>`;
}

function renderContributorByline(test, contributorData) {
  const attribution = contributorData?.attributions?.[test.id];
  if (!attribution) return [];
  const profilesById = contributorData.profilesById;
  const author = profilesById.get(attribution.author);
  if (!author) return [];
  const coContributors = attribution.contributors.map((id) => profilesById.get(id)).filter(Boolean);

  const maxAvatars = 6;
  const avatarParts = [renderBylineAvatar(author, " test-byline-avatar--author", "Original author")];
  for (const profile of coContributors.slice(0, maxAvatars - 1)) {
    avatarParts.push(renderBylineAvatar(profile, "", "Co-contributor"));
  }
  const overflow = coContributors.length - (maxAvatars - 1);
  if (overflow > 0) avatarParts.push(`<span className="test-byline-avatar test-byline-more">+${overflow}</span>`);

  const authorLink = `<a href="${jsxAttr(contributorLinkTarget(author))}">${jsxText(author.name)}</a>`;
  let coText = "";
  if (coContributors.length === 1) {
    coText = ` with <a href="${jsxAttr(contributorLinkTarget(coContributors[0]))}">${jsxText(coContributors[0].name)}</a>`;
  } else if (coContributors.length > 1) {
    coText = ` with ${coContributors.length} co-contributors`;
  }

  return [
    `<div className="test-byline">` +
      `<div className="test-byline-avatars">${avatarParts.join("")}</div>` +
      `<div className="test-byline-meta"><span className="test-byline-text">Contributed by ${authorLink}${coText}</span>` +
      `<a className="test-byline-link" href="/contributors">All contributors →</a></div>` +
      `</div>`,
    "",
  ];
}

function normalizeWhitespace(value) {
  return String(value ?? "").replace(/\s+/g, " ").trim();
}

function trimDescription(value, max = 300) {
  // Leading headings (e.g. "# Policy name" or "## Description") are labels, not summary text.
  const lines = String(value ?? "").split("\n");
  while (lines.length > 0 && /^\s*(?:#{1,6}\s|$)/.test(lines[0])) lines.shift();
  const prose = lines
    .join("\n")
    // Markdown hard line breaks ("text\" at end of line) and escapes ("\*") are not plain text.
    .replace(/\\(?=\r?$)/gm, "")
    .replace(/\\([!-/:-@[-`{-~])/g, "$1");
  const text = normalizeWhitespace(prose)
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/#{2,6}\s+/g, "")
    .replace(/<br\s*\/?\s*>/gi, " ");
  if (text.length <= max) return text;
  return `${text.slice(0, max - 1).trim()}…`;
}

function unique(values) {
  return [...new Set(values.filter(Boolean).map((value) => String(value).trim()).filter(Boolean))];
}

function normalizeMarkdown(markdown) {
  return markdown
    // Test.<ID>.md files are saved with a UTF-8 BOM; it would otherwise leak into the page text.
    .replace(/^\uFEFF/, "")
    // extractSection() below rejoins split lines with plain "\n"; leaving CRLF
    // here would make that rejoined text byte-different from this string, so
    // the duplicate-section .includes() guards in renderTestPage() would never
    // match and every section would be emitted twice.
    .replace(/\r\n/g, "\n")
    .replace(/<br>/gi, "<br />")
    .replace(/\[([^\]]+)\]\(#[^)]+\)/g, "$1")
    // MDX has no autolinks ("<https://...>" parses as JSX). A URL with a {placeholder} is not a real
    // link (and its braces would parse as an expression), so show it as code.
    .replace(/<(https?:\/\/[^\s<>]+)>/g, (match, url) => (/[{}]/.test(url) ? `\`${url}\`` : `[${url}](${url})`))
    // Sibling help files link to each other as "./Test-MtX.md", which does not exist under docs/tests.
    .replace(/\]\(\.\/(Test-Mt[A-Za-z0-9]+)\.md\)/g, "](/docs/commands/$1)");
}

function parseCommentHelp(content) {
  const match = content.match(/<#([\s\S]*?)#>/);
  if (!match) return {};
  const sections = {};
  let current = null;
  for (const rawLine of match[1].split(/\r?\n/)) {
    const line = rawLine.replace(/^\s*#?\s?/, "").trimEnd();
    const header = line.match(/^\.(\w+)\b\s*(.*)$/);
    if (header) {
      current = header[1].toLowerCase();
      sections[current] = [];
      if (header[2]) sections[current].push(header[2].trim());
      continue;
    }
    if (current) sections[current].push(line);
  }
  for (const key of Object.keys(sections)) {
    sections[key] = sections[key].join("\n").trim();
  }
  return sections;
}

function stripGeneratedResultPlaceholder(markdown) {
  return markdown
    .replace(/<!--- Results --->[\s\S]*$/i, "")
    .replace(/%TestResult%/g, "")
    .trim();
}

function extractSection(markdown, headingPattern) {
  const lines = markdown.split(/\r?\n/);
  const start = lines.findIndex((line) => headingPattern.test(line.trim()));
  if (start === -1) return "";
  const body = [];
  for (let index = start + 1; index < lines.length; index += 1) {
    if (/^#{2,6}\s+/.test(lines[index])) break;
    body.push(lines[index]);
  }
  return body.join("\n").trim();
}

// The catalog comes from Get-MtTest (the authoritative reader of the [MaesterTest] attribute), exported
// to JSON by build/docs/Export-MtTestCatalogForDocs.ps1. Resolution order:
//   1. --catalog <path> or MAESTER_TEST_CATALOG: must exist (used by CI after running the exporter).
//   2. Otherwise run the exporter with pwsh into website/.generated/test-catalog.json.
// Returns null when no catalog can be produced (for example pwsh or Microsoft.Graph.Authentication is
// not installed), so `npm start` still works with the committed pages.
function catalogArgument() {
  const index = process.argv.indexOf("--catalog");
  if (index !== -1) return process.argv[index + 1] ?? "";
  return process.env.MAESTER_TEST_CATALOG ?? "";
}

function loadCatalog() {
  const explicit = catalogArgument();
  if (explicit) {
    const path = resolve(process.cwd(), explicit);
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- path is supplied by the caller (CI workflow or developer)
    if (!existsSync(path)) throw new Error(`Test catalog not found at ${path}. Run build/docs/Export-MtTestCatalogForDocs.ps1 first.`);
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- same caller-supplied path as above
    return JSON.parse(readFileSync(path, "utf8")).Tests;
  }

  const result = spawnSync("pwsh", ["-NoProfile", "-NonInteractive", "-File", exporterPath, "-OutputPath", defaultCatalogPath], {
    cwd: repoRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  if (result.status === 0 && existsSync(defaultCatalogPath)) {
    return JSON.parse(readFileSync(defaultCatalogPath, "utf8")).Tests;
  }
  const reason = result.error ? result.error.message : (result.stderr || result.stdout || "").trim().split("\n").slice(-3).join(" ");
  console.warn(`Could not export the Maester test catalog (${reason || `pwsh exited with ${result.status}`}).`);
  console.warn("Test docs need PowerShell 7 and the Microsoft.Graph.Authentication module to read the native tests.");
  return null;
}

function suiteFor(test) {
  const suite = String(test.Suite ?? "").toLowerCase();
  if (suite !== "other" && Object.hasOwn(suiteConfig, suite)) return suite;
  // Suites without their own docs section (e.g. XSPM, whose tests use MT IDs) are listed with Maester.
  if (/^(MT\.|AZDO\.)/i.test(test.Id) || test.Source === "Maester") return "maester";
  return "other";
}

// Category from the [MaesterTest] attribute. Benchmark suites set it to the suite name, which says
// nothing on a page that already lists the suite, so fall back to the most specific tag (the 2.x rule).
function categoryFor(test, tags) {
  const category = String(test.Category ?? "").trim();
  const uninformative = [test.Suite, test.Source].filter(Boolean).map((value) => String(value).toLowerCase());
  if (category && !uninformative.includes(category.toLowerCase())) return category;
  // Excludes benchmark-version tags (e.g. "CIS M365 v7.0.0", "CIS GitHub v1.2.0") too, so a
  // suite-level version tag never wins over a more specific "CIS E3 Level 1" tag.
  const candidates = tags.filter((tag) => !/^(MT\.|CIS\.|CISA\.|MS\.|EIDSCA\.|ORCA\.|AD-|AZDO\.|L1$|L2$|Maester$|CIS$|CISA$|ORCA$|EIDSCA$|AD$|CIS\s+\S+\s+v[\d.]+$)/i.test(tag));
  // CIS tests carry both "CIS E3" and "CIS E3 Level 1"; the level-specific tag is the more useful one.
  const levelTag = candidates.find((tag) => /\bLevel\s*\d\b/i.test(tag));
  if (levelTag ?? candidates[0]) return levelTag ?? candidates[0];
  // Otherwise the folder the test lives in, below the suite folder (e.g. tests/cisa/exchange -> "exchange").
  const folders = String(test.File ?? "").split("/").slice(1, -1).filter((part) => !/^(maester|cis|cisa|eidsca|orca)$/i.test(part));
  return folders[0] ?? "General";
}

// CIS benchmark levels (L1/L2) live in tags ("L1"/"L2" or "CIS E3 Level 1"). Prefix the level so
// generated titles stay consistent, e.g. "(L1) Ensure ...".
function titleFor(test, tags) {
  const title = String(test.Title ?? "").trim();
  if (!test.Id.startsWith("CIS.") || /^\(L\d\)\s*/i.test(title)) return title;
  const levelTag = tags.find((tag) => /^L[12]$/i.test(tag));
  const levelFromSuite = tags.map((tag) => tag.match(/level\s*([12])\b/i)?.[1]).find(Boolean);
  const level = levelTag ? levelTag.toUpperCase() : levelFromSuite ? `L${levelFromSuite}` : null;
  return level ? `(${level}) ${title}` : title;
}

let sourceFileIndex;
// Every PowerShell function by name: module files are named after their function, native tests are
// named Test.<ID>.ps1, so the catalog supplies those.
function sourceFileFor(functionName) {
  if (!sourceFileIndex) {
    sourceFileIndex = new Map(
      walkFiles(join(repoRoot, "powershell"), (path) => path.endsWith(".ps1")).map((file) => [file.split(sep).pop().replace(/\.ps1$/i, "").toLowerCase(), file]),
    );
    for (const test of catalogTests ?? []) {
      if (test.FunctionName && test.File) sourceFileIndex.set(test.FunctionName.toLowerCase(), join(repoRoot, test.File));
    }
  }
  return sourceFileIndex.get(functionName.toLowerCase()) ?? "";
}

function sourceUrlFor(repoRelativePath) {
  return `${sourceBaseUrl}${repoRelativePath.split("/").map(encodeURIComponent).join("/")}`;
}

// Link the test function to its command reference page when one exists, otherwise to its source.
function commandLinkFor(functionName, functionPath, commandsRoot) {
  if (!functionName) return "";
  functionPath ||= sourceFileFor(functionName);
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- path is built from repo constants and a PowerShell function name
  if (existsSync(join(commandsRoot, `${functionName}.mdx`))) return `/docs/commands/${functionName}`;
  return functionPath ? sourceUrlFor(toPosixPath(relative(repoRoot, functionPath))) : "";
}

// Released test docs are a frozen snapshot, but their command pages are re-synced by
// build/Update-CommandReference.ps1. Repoint links to command pages that no longer exist
// in that version so the Docusaurus broken-link check keeps passing.
function relinkVersionedCommandReferences(versionedTestsRoot, writes) {
  const versionedCommandsRoot = join(dirname(versionedTestsRoot), "commands");
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- versioned docs paths are derived from versions.json inside the repo
  if (!existsSync(versionedTestsRoot) || !existsSync(versionedCommandsRoot)) return;
  for (const file of walkFiles(versionedTestsRoot, (path) => path.endsWith(".md"))) {
    const content = readFileSync(file, "utf8");
    const updated = content.replace(/\]\(\/docs\/commands\/([A-Za-z0-9-]+)\)/g, (match, functionName) => {
      const link = commandLinkFor(functionName, "", versionedCommandsRoot);
      return link ? `](${link})` : match;
    });
    if (updated === content) continue;
    if (checkMode) writes.push(file);
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- file comes from walkFiles() over the repo's versioned docs
    else writeFileSync(file, updated);
  }
}

