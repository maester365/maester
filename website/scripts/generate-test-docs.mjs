function ensureDir(path) {
  mkdirSync(path, { recursive: true });
}

function writeGenerated(path, content, writes) {
  ensureDir(dirname(path));
  const normalized = `${content.trimEnd()}\n`;
  if (checkMode) {
    const existing = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (existing !== normalized) writes.push(path);
    return;
  }
  writeFileSync(path, normalized);
}

function clearGeneratedDocs() {
  if (checkMode) return;
  for (const suite of Object.keys(suiteConfig)) {
    const suiteDir = join(docsTestsRoot, suite);
    if (existsSync(suiteDir)) rmSync(suiteDir, { recursive: true, force: true });
  }
  const tagsDir = join(docsTestsRoot, "tags");
  if (existsSync(tagsDir)) rmSync(tagsDir, { recursive: true, force: true });
}

function main() {
  catalogTests = loadCatalog();
  if (!catalogTests) {
    if (checkMode) {
      console.error("Cannot check the generated test docs without the test catalog.");
      process.exit(1);
    }
    console.warn("Skipping test docs generation; the committed pages in website/docs/tests are used as they are.");
    return;
  }
  const tests = buildInventory(catalogTests);
  const writes = [];
  clearGeneratedDocs();

  const contributorData = computeContributorData(tests, { updateAliases: !checkMode });
  contributorData.profilesById = new Map(contributorData.profiles.map((profile) => [profile.id, profile]));
  // Tests not yet in the released docs version only resolve under /docs/next/.
  const releasedVersions = JSON.parse(readFileSync(join(websiteRoot, "versions.json"), "utf8"));
  const versionedTestsRoot = releasedVersions[0] ? join(websiteRoot, "versioned_docs", `version-${releasedVersions[0]}`, "tests") : "";
  const docPathFor = (test) =>
    versionedTestsRoot && existsSync(join(versionedTestsRoot, test.suite, `${test.id}.md`))
      ? `/docs/tests/${test.id}`
      : `/docs/next/tests/${test.id}`;
  const testTitles = Object.fromEntries(tests.map((test) => [test.id, { title: test.title, path: docPathFor(test) }]));
  writeGenerated(snapshotPath, `${JSON.stringify({ profiles: contributorData.profiles, attributions: contributorData.attributions, tests: testTitles }, null, 2)}\n`, writes);

  writeGenerated(join(docsTestsRoot, "readme.md"), renderRootIndex(tests), writes);
  writeGenerated(join(docsTestsRoot, "tags", "readme.md"), renderTagsIndex(tests), writes);

  for (const suite of Object.keys(suiteConfig)) {
    const suiteTests = tests.filter((test) => test.suite === suite);
    if (suiteTests.length === 0) continue;
    writeGenerated(join(docsTestsRoot, suite, "readme.md"), renderSuiteIndex(suite, suiteTests), writes);
    for (const test of suiteTests) {
      writeGenerated(pagePathFor(test), renderTestPage(test, contributorData), writes);
    }
  }
  if (versionedTestsRoot) relinkVersionedCommandReferences(versionedTestsRoot, writes);

  if (checkMode && writes.length > 0) {
    console.error(`Generated test docs are stale. Run npm run generate-test-docs. Stale files: ${writes.length}`);
    for (const file of writes.slice(0, 20)) console.error(`- ${toPosixPath(relative(repoRoot, file))}`);
    process.exit(1);
  }

  console.log(`${checkMode ? "Checked" : "Generated"} ${tests.length} test documentation pages.`);
}

main();
