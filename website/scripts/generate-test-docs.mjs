function walkFiles(dir, predicate = () => true) {
  if (!existsSync(dir)) return [];
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walkFiles(path, predicate));
    else if (predicate(path)) files.push(path);
  }
  return files.sort();
}

function yamlQuote(value) {
  // The MDX loader writes frontmatter strings into JavaScript without escaping backslashes, so
  // "domain\username" becomes an invalid "\u" escape and fails the build. Doubling the backslash
  // would fix that but shows "\\" in the page metadata, which Docusaurus parses separately, so
  // swap in a look-alike (U+2216 SET MINUS) instead.
  return JSON.stringify(String(value ?? "").replaceAll("\\", "\u2216"));
}

// Source paths are embedded in generated docs and used as contributors.mjs
// lookup keys against git's always-forward-slash paths; node:path's relative()
// returns native separators, which would silently break both on Windows
// (backslashes never match, so every test's contributor attribution is empty).
function toPosixPath(value) {
  return sep === "/" ? value : value.split(sep).join("/");
}

function escapeTable(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("<br>", "<br />")
    .replaceAll("\n", "<br />");
}

function jsxText(value) {
  return String(value ?? "").replace(/[&<>{}]/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "{": "&#123;", "}": "&#125;" }[ch]));
}

function jsxAttr(value) {
  return jsxText(value).replaceAll('"', "&quot;");
}

function contributorLinkTarget(profile) {
  return profile ? `/contributors/${profile.id.toLowerCase()}` : "/contributors";
}

function renderBylineAvatar(profile, extraClass, roleLabel) {
  if (!profile) return "";
  const title = `${profile.name}${roleLabel ? ` · ${roleLabel}` : ""}`;
  const inner = profile.avatar
    ? `<img src="${jsxAttr(profile.avatar)}" alt="${jsxAttr(profile.name)}" width="28" height="28" loading="lazy" decoding="async" />`
    : `<span class="test-byline-initials">${jsxText(profile.initials ?? "?")}</span>`;
  return `<a class="test-byline-avatar${extraClass}" href="${jsxAttr(contributorLinkTarget(profile))}" title="${jsxAttr(title)}">${inner}</a>`;
}

function renderContributorByline(test, contributorData) {
  const attribution = contributorData?.attributions?.[test.id];
  if (!attribution) return [];
  const profilesById = contributorData.profilesById;
  const author = profilesById.get(attribution.author);
  if (!author) return [];
  const coContributors = attribution.contributors.map((id) => profilesById.get(id)).filter(Boolean);

  const maxAvatars = 6;
  const avatarParts = [renderBylineAvatar(author, " test-byline-avatar--author", "Original author")];
  for (const profile of coContributors.slice(0, maxAvatars - 1)) {
    avatarParts.push(renderBylineAvatar(profile, "", "Co-contributor"));
  }
  const overflow = coContributors.length - (maxAvatars - 1);
  if (overflow > 0) avatarParts.push(`<span class="test-byline-avatar test-byline-more">+${overflow}</span>`);

  const authorLink = `<a href="${jsxAttr(contributorLinkTarget(author))}">${jsxText(author.name)}</a>`;
  let coText = "";
  if (coContributors.length === 1) {
    coText = ` with <a href="${jsxAttr(contributorLinkTarget(coContributors[0]))}">${jsxText(coContributors[0].name)}</a>`;
  } else if (coContributors.length > 1) {
    coText = ` with ${coContributors.length} co-contributors`;
  }

  return [
    `<div class="test-byline">` +
      `<div class="test-byline-avatars">${avatarParts.join("")}</div>` +
      `<div class="test-byline-meta"><span class="test-byline-text">Contributed by ${authorLink}${coText}</span>` +
      `<a class="test-byline-link" href="/contributors">All contributors →</a></div>` +
      `</div>`,
    "",
  ];
}

// Cut a title at a word boundary so the page title stays readable in search results.
function shorten(text, max) {
  if (text.length <= max) return text;
  return `${text.slice(0, text.lastIndexOf(" ", max)).replace(/[,;:\s]+$/, "")}…`;
}

function normalizeWhitespace(value) {
  return String(value ?? "").replace(/\s+/g, " ").trim();
}

function trimDescription(value, max = 300) {
  // Leading headings (e.g. "# Policy name" or "## Description") are labels, not summary text.
  const lines = String(value ?? "").split("\n");
  while (lines.length > 0 && /^\s*(?:#{1,6}\s|$)/.test(lines[0])) lines.shift();
  const prose = lines
    .join("\n")
    // Markdown hard line breaks ("text\" at end of line) and escapes ("\*") are not plain text.
    .replace(/\\(?=\r?$)/gm, "")
    .replace(/\\([!-/:-@[-`{-~])/g, "$1");
  const text = normalizeWhitespace(prose)
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/#{2,6}\s+/g, "")
    .replace(/<br\s*\/?\s*>/gi, " ");
  if (text.length <= max) return text;
  return `${text.slice(0, max - 1).trim()}…`;
}

function unique(values) {
  return [...new Set(values.filter(Boolean).map((value) => String(value).trim()).filter(Boolean))];
}

function normalizeMarkdown(markdown) {
  return markdown
    // Test.<ID>.md files are saved with a UTF-8 BOM; it would otherwise leak into the page text.
    .replace(/^\uFEFF/, "")
    // extractSection() below rejoins split lines with plain "\n"; leaving CRLF
    // here would make that rejoined text byte-different from this string, so
    // the duplicate-section .includes() guards in renderTestPage() would never
    // match and every section would be emitted twice.
    .replace(/\r\n/g, "\n")
    .replace(/<br>/gi, "<br />")
    .replace(/\[([^\]]+)\]\(#[^)]+\)/g, "$1")
    // MDX has no autolinks ("<https://...>" parses as JSX). A URL with a {placeholder} is not a real
    // link (and its braces would parse as an expression), so show it as code.
    .replace(/<(https?:\/\/[^\s<>]+)>/g, (match, url) => (/[{}]/.test(url) ? `\`${url}\`` : `[${url}](${url})`))
    // Sibling help files link to each other as "./Test-MtX.md", which does not exist under docs/tests.
    .replace(/\]\(\.\/(Test-Mt[A-Za-z0-9]+)\.md\)/g, "](/docs/commands/$1)");
}

function parseCommentHelp(content) {
  const match = content.match(/<#([\s\S]*?)#>/);
  if (!match) return {};
  const sections = {};
  let current = null;
  for (const rawLine of match[1].split(/\r?\n/)) {
    const line = rawLine.replace(/^\s*#?\s?/, "").trimEnd();
    const header = line.match(/^\.(\w+)\b\s*(.*)$/);
    if (header) {
      current = header[1].toLowerCase();
      sections[current] = [];
      if (header[2]) sections[current].push(header[2].trim());
      continue;
    }
    if (current) sections[current].push(line);
  }
  for (const key of Object.keys(sections)) {
    sections[key] = sections[key].join("\n").trim();
  }
  return sections;
}

function stripGeneratedResultPlaceholder(markdown) {
  return markdown
    .replace(/<!--- Results --->[\s\S]*$/i, "")
    .replace(/%TestResult%/g, "")
    .trim();
}

function extractSection(markdown, headingPattern) {
  const lines = markdown.split(/\r?\n/);
  const start = lines.findIndex((line) => headingPattern.test(line.trim()));
  if (start === -1) return "";
  const body = [];
  for (let index = start + 1; index < lines.length; index += 1) {
    if (/^#{2,6}\s+/.test(lines[index])) break;
    body.push(lines[index]);
  }
  return body.join("\n").trim();
}

// The catalog comes from Get-MtTest (the authoritative reader of the [MaesterTest] attribute), exported
// to JSON by build/docs/Export-MtTestCatalogForDocs.ps1: --catalog <path> or MAESTER_TEST_CATALOG, or else
// website/src/data/test-catalog.json, which scripts/prepare-data.mjs exports before each dev server and build.
function catalogArgument() {
  const index = process.argv.indexOf("--catalog");
  if (index !== -1) return process.argv[index + 1] ?? "";
  return process.env.MAESTER_TEST_CATALOG ?? "";
}

// Returns the export: { Taxonomy, Frameworks, Tests }. Taxonomy holds the display names of the product,
// feature and area keys and of the ATT&CK techniques that the tests use. Frameworks holds the name of each
// benchmark a suite implements, by the key a test's Benchmark uses.
function loadCatalog() {
  const path = catalogArgument() ? resolve(process.cwd(), catalogArgument()) : defaultCatalogPath;
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- path is the exported catalog or one supplied by the caller
  if (!existsSync(path)) throw new Error(`Test catalog not found at ${path}. Run npm run export-catalog first.`);
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- same path as above
  return JSON.parse(readFileSync(path, "utf8"));
}

function suiteFor(test) {
  const suite = String(test.Suite ?? "").toLowerCase();
  if (suite !== "other" && Object.hasOwn(suiteConfig, suite)) return suite;
  // Suites without their own docs section (e.g. XSPM, whose tests use MT IDs) are listed with Maester.
  if (/^(MT\.|AZDO\.)/i.test(test.Id) || test.Source === "Maester") return "maester";
  return "other";
}

// Display names of the taxonomy keys, from the export's Taxonomy. A test says what it is about with keys
// (Product = 'entra', Feature = 'conditional-access'); a key the taxonomy does not list is shown as written.
let taxonomyNames = { products: new Map(), features: new Map(), areas: new Map(), techniques: new Map() };
function loadTaxonomyNames(taxonomy) {
  taxonomyNames = {
    products: new Map((taxonomy?.Products ?? []).map((product) => [product.Key, product.Name])),
    features: new Map((taxonomy?.Features ?? []).map((feature) => [`${feature.Product}|${feature.Key}`, feature.Name])),
    areas: new Map((taxonomy?.Areas ?? []).map((area) => [area.Key, area.Name])),
    techniques: new Map((taxonomy?.Attack?.Techniques ?? []).map((technique) => [technique.Id, technique.Name])),
  };
}

function productNameFor(key) {
  return key ? taxonomyNames.products.get(key) ?? key : "";
}

function featureNameFor(test) {
  return test.Feature ? taxonomyNames.features.get(`${test.Product}|${test.Feature}`) ?? test.Feature : "";
}

function areaNameFor(key) {
  return key ? taxonomyNames.areas.get(key) ?? key : "";
}

// "T1110 Brute Force" for a technique the pinned ATT&CK release names, the ID alone otherwise.
function mitreLabelFor(id) {
  const name = taxonomyNames.techniques.get(id);
  return name ? `${id} ${name}` : id;
}

// A test of a suite that implements a published benchmark has Benchmark in the export, from the framework file
// of its suite (tests/<suite>/frameworks/<key>.json): Framework (a key), Version, Requirement and the
// requirement's own facts, such as Level and Profile for CIS or Criticality and Upstream for CISA.
let frameworkNames = new Map();
function loadFrameworkNames(frameworks) {
  frameworkNames = new Map((frameworks ?? []).map((framework) => [framework.Key, framework.Name || framework.Key]));
}

// The CIS benchmark level (L1/L2) is a fact of the requirement, not an attribute of the test. Prefix it so
// generated titles stay consistent, e.g. "(L1) Ensure ...".
function titleFor(test) {
  const title = String(test.Title ?? "").trim();
  const level = String(test.Benchmark?.Level ?? "").toUpperCase();
  if (!/^L\d$/.test(level) || /^\(L\d\)\s*/i.test(title)) return title;
  return `(${level}) ${title}`;
}

// "CIS Microsoft 365 Foundations Benchmark (version 7.0.0), requirement 5.2.2.3". A test supports a
// requirement; the page never says that passing it makes a tenant compliant with the benchmark.
function benchmarkLabelFor(benchmark) {
  const name = frameworkNames.get(benchmark.Framework) ?? benchmark.Framework;
  const version = benchmark.Version ? ` (version ${benchmark.Version})` : "";
  return `${name}${version}, requirement ${benchmark.Requirement}`;
}

// Where the requirement stands in the upstream baseline today, when the framework file records it.
function upstreamLabelFor(upstream) {
  switch (upstream?.Status) {
    case "Current":
      return upstream.Id ?? "";
    case "Moved":
      return `Moved to ${upstream.Id}${upstream.From ? ` (was ${upstream.From})` : ""}`;
    case "Removed":
      return `Removed${upstream.From ? ` (was ${upstream.From})` : ""}`;
    default:
      return "";
  }
}

let sourceFileIndex;
// Every PowerShell function by name: module files are named after their function, native tests are
// named Test.<ID>.ps1, so the catalog supplies those.
function sourceFileFor(functionName) {
  if (!sourceFileIndex) {
    sourceFileIndex = new Map(
      walkFiles(join(repoRoot, "powershell"), (path) => path.endsWith(".ps1")).map((file) => [file.split(sep).pop().replace(/\.ps1$/i, "").toLowerCase(), file]),
    );
    for (const test of catalogTests ?? []) {
      if (test.FunctionName && test.File) sourceFileIndex.set(test.FunctionName.toLowerCase(), join(repoRoot, test.File));
    }
  }
  return sourceFileIndex.get(functionName.toLowerCase()) ?? "";
}

function sourceUrlFor(repoRelativePath) {
  return `${sourceBaseUrl}${repoRelativePath.split("/").map(encodeURIComponent).join("/")}`;
}

// Link the test function to its command reference page when one exists, otherwise to its source.
function commandLinkFor(functionName, functionPath, commandsRoot) {
  if (!functionName) return "";
  functionPath ||= sourceFileFor(functionName);
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- path is built from repo constants and a PowerShell function name
  if (existsSync(join(commandsRoot, `${functionName}.mdx`))) return `/docs/commands/${functionName}`;
  return functionPath ? sourceUrlFor(toPosixPath(relative(repoRoot, functionPath))) : "";
}

let catalogTests = null;

function buildInventory(catalog) {
  const testsById = new Map();
  for (const test of catalog) {
    const key = test.Id.toLowerCase();
    if (testsById.has(key)) continue;
    const testFile = join(repoRoot, test.File);
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- paths come from the exported catalog of repo files
    const help = existsSync(testFile) ? parseCommentHelp(readFileSync(testFile, "utf8")) : {};
    const markdownFile = test.MarkdownPath ? join(repoRoot, test.MarkdownPath) : "";
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- paths come from the exported catalog of repo files
    const markdown = markdownFile && existsSync(markdownFile) ? normalizeMarkdown(stripGeneratedResultPlaceholder(readFileSync(markdownFile, "utf8"))) : "";
    const helpDescription = normalizeMarkdown(help.description ?? "");
    // Tag holds the labels the test's author wrote. LegacyTag holds the tags the test carried in
    // Maester 2.x, which -Tag still matches; they are listed on the tags page and used as search keywords.
    const tags = unique(test.Tag ?? []).sort((a, b) => a.localeCompare(b));
    const legacyTags = unique(test.LegacyTag ?? []).sort((a, b) => a.localeCompare(b));
    const title = titleFor(test);
    // Search engines show about 155 characters: the first real sentence or two, as plain text.
    let description = summarize(markdown) || summarize(helpDescription) || summarize(help.synopsis ?? "");
    const about = [productNameFor(test.Product), featureNameFor(test)].filter(Boolean).join(", ");
    if (description.length < 70) description = shorten(`${title.replace(/\.$/, "")}. A Maester check${about ? ` for ${about}` : ""}.`, 155);
    const defaultHelpUrl = `https://maester.dev/docs/tests/${test.Id}`;
    testsById.set(key, {
      id: test.Id,
      title,
      description,
      severity: test.Severity || "Unknown",
      suite: suiteFor(test),
      product: productNameFor(test.Product),
      relatedProducts: (test.RelatedProduct ?? []).map(productNameFor),
      feature: featureNameFor(test),
      area: areaNameFor(test.Area),
      resourceType: test.ResourceType ?? "",
      userImpact: test.UserImpact ?? "",
      implementationCost: test.ImplementationCost ?? "",
      mitre: (test.Mitre ?? []).map(mitreLabelFor),
      benchmark: test.Benchmark ?? null,
      controls: test.Control ?? [],
      tags,
      legacyTags,
      services: test.Service ?? [],
      licenses: test.License ?? [],
      permissions: test.Permission ?? [],
      lifecycle: test.Lifecycle || "Stable",
      replacedBy: test.ReplacedBy ?? "",
      longRunning: Boolean(test.LongRunning),
      instanceSource: test.InstanceSource ?? "",
      helpUrl: test.HelpUrl && test.HelpUrl.toLowerCase() !== defaultHelpUrl.toLowerCase() ? test.HelpUrl : "",
      authors: test.Author ?? [],
      contributors: test.Contributor ?? [],
      functionName: test.FunctionName ?? "",
      sourceFunctionFile: test.File,
      sourceMarkdownFile: test.MarkdownPath ?? "",
      synopsis: help.synopsis ?? "",
      helpDescription,
      markdown,
      remediation: extractSection(markdown, /^#{2,6}\s+Remediation action:?$/i),
      relatedLinks: extractSection(markdown, /^#{2,6}\s+Related links?$/i),
      commandLink: commandLinkFor(test.FunctionName ?? "", testFile, docsCommandsRoot),
    });
  }
  return [...testsById.values()].sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));
}

