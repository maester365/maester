function ensureDir(path) {
  mkdirSync(path, { recursive: true });
}

function writeGenerated(path, content, writes) {
  ensureDir(dirname(path));
  const normalized = `${content.trimEnd()}\n`;
  if (checkMode) {
    const existing = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (existing !== normalized) writes.push(path);
    return;
  }
  writeFileSync(path, normalized);
}

function clearGeneratedDocs() {
  rmSync(docsTestsRoot, { recursive: true, force: true });
}

let releasedTests = new Set();

export function main() {
  const catalog = loadCatalog();
  catalogTests = catalog.Tests;
  loadTaxonomyNames(catalog.Taxonomy);
  loadFrameworkNames(catalog.Frameworks);
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- repo constant
  releasedTests = new Set(Object.keys(JSON.parse(readFileSync(versionsPath, "utf8")).tests));
  const tests = buildInventory(catalogTests);
  // Checks of one family often share their documentation: lead those descriptions with the check's own title.
  const seen = new Map();
  for (const test of tests) seen.set(test.description, (seen.get(test.description) ?? 0) + 1);
  for (const test of tests) {
    if (seen.get(test.description) > 1) test.description = shorten(`${test.title.replace(/\.$/, "")}: ${test.description}`, 155);
  }
  const writes = [];
  clearGeneratedDocs();

  // --update-aliases records the GitHub accounts of new commit emails in contributors/email-aliases.json; a site
  // build looks them up again each time and only reads the file.
  const updateAliases = process.argv.includes("--update-aliases");
  const contributorData = computeContributorData(tests, { updateAliases, log: updateAliases ? console.log : () => {} });
  contributorData.profilesById = new Map(contributorData.profiles.map((profile) => [profile.id, profile]));
  // The explorer's data, with who wrote and improved each check (the same credits as the test pages' bylines).
  const explorer = writeExplorerData(catalog, releasedTests, contributorData);
  const testTitles = Object.fromEntries(tests.map((test) => [test.id, { title: test.title, path: `/docs/tests/${test.id}` }]));
  writeGenerated(snapshotPath, `${JSON.stringify({ profiles: contributorData.profiles, attributions: contributorData.attributions, tests: testTitles }, null, 2)}\n`, writes);

  writeGenerated(join(docsTestsRoot, "index.mdx"), renderRootIndex(explorer), writes);
  writeGenerated(join(docsTestsRoot, "overview.mdx"), renderOverview(explorer), writes);
  writeGenerated(join(docsTestsRoot, "attack.mdx"), renderAttackPage(explorer), writes);
  for (const product of explorer.products) writeGenerated(join(docsTestsRoot, "products", `${product.key}.mdx`), renderProductPage(explorer, product), writes);
  for (const framework of explorer.frameworks) writeGenerated(join(docsTestsRoot, "frameworks", `${framework.key}.mdx`), renderFrameworkPage(framework), writes);
  // Each pack test's own text (Description, Remediation), from the pack's catalog.
  const packText = new Map((catalog.Packs ?? []).flatMap((p) => p.Tests.map((t) => [t.Id, t])));
  for (const pack of explorer.packs) {
    writeGenerated(join(docsTestsRoot, "packs", `${pack.slug}.mdx`), renderPackPage(pack), writes);
    for (const test of explorer.tests.filter((t) => t.pack === pack.code)) writeGenerated(join(docsTestsRoot, "packs", pack.slug, `${test.id}.md`), renderPackTestPage(pack, test, explorer, packText.get(test.id)), writes);
  }
  writeGenerated(join(docsTestsRoot, "tags.md"), renderTagsIndex(tests), writes);

  for (const suite of Object.keys(suiteConfig)) {
    const suiteTests = tests.filter((test) => test.suite === suite);
    if (suiteTests.length === 0) continue;
    writeGenerated(join(docsTestsRoot, suite, "index.mdx"), renderSuiteIndex(suite), writes);
    for (const test of suiteTests) {
      writeGenerated(pagePathFor(test), renderTestPage(test, contributorData), writes);
    }
  }
  return tests.length;
}

