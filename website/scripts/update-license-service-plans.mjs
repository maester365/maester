// Builds website/src/data/license-service-plans.json from Microsoft's "Product names and service plan
// identifiers for licensing" page. The test builder uses it to look up the service plan names that go in
// [MaesterTest(License = ...)].
//
// The source is the Markdown of
// https://learn.microsoft.com/entra/identity/users/licensing-service-plan-reference in MicrosoftDocs/entra-docs.
// A scheduled workflow (.github/workflows/update-license-service-plans.yaml) runs this every day and opens a
// pull request when Microsoft adds or changes a plan.
//
//   node scripts/update-license-service-plans.mjs            download and rewrite the data file
//   node scripts/update-license-service-plans.mjs <file.md>  parse a local copy instead
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

export const SOURCE_URL = "https://raw.githubusercontent.com/MicrosoftDocs/entra-docs/main/docs/identity/users/licensing-service-plan-reference.md";
const GUID = /\(?\s*([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})\s*\)?/;
// What the License attribute accepts for one plan name (MaesterTestSchema.psd1).
const TOKEN = /^[A-Za-z0-9_-]+$/;

const cells = (line) => line.trim().replace(/^\||\|$/g, "").split("|").map((c) => c.trim());

// "NAME (guid)<br/>NAME (guid)" -> [{ name, guid }]
function entries(cell) {
  return cell
    .split(/<br\s*\/?>/i)
    .map((part) => {
      const match = GUID.exec(part);
      if (!match) return null;
      return { name: part.slice(0, match.index).trim(), guid: match[1].toLowerCase() };
    })
    .filter(Boolean);
}

export function parse(markdown) {
  const lines = markdown.split(/\r?\n/);
  const start = lines.findIndex((l) => /^\|\s*Product name\s*\|\s*String ID\s*\|\s*GUID\s*\|\s*Service plans included\s*\|/i.test(l));
  if (start < 0) throw new Error("The product table was not found. The page layout may have changed.");
  const products = [];
  const plans = new Map();
  let skipped = 0;
  for (let i = start + 2; i < lines.length && lines[i].trim().startsWith("|"); i++) {
    const row = cells(lines[i]);
    if (row.length < 5) continue;
    const [name, stringId, guid, included, friendly] = row;
    const productIndex = products.length;
    products.push([name, stringId.replace(/\s+/g, ""), guid.toLowerCase()]);
    const friendlyByGuid = new Map(entries(friendly).map((e) => [e.guid, e.name]));
    for (const entry of entries(included)) {
      // The page has stray spaces inside some names ("Auditing_10Year_ Retention_ Add_On").
      const plan = entry.name.replace(/\s+/g, "");
      if (!TOKEN.test(plan)) {
        skipped++;
        continue;
      }
      const key = plan.toUpperCase();
      if (!plans.has(key)) plans.set(key, { name: plan, guids: new Set(), friendly: "", products: new Set() });
      const record = plans.get(key);
      record.guids.add(entry.guid);
      if (!record.friendly && friendlyByGuid.get(entry.guid)) record.friendly = friendlyByGuid.get(entry.guid);
      record.products.add(productIndex);
    }
  }
  if (products.length < 100 || plans.size < 100) throw new Error(`Only ${products.length} products and ${plans.size} plans were parsed. Refusing to write.`);
  return {
    note: "Generated by website/scripts/update-license-service-plans.mjs from " + SOURCE_URL + ". Do not edit.",
    // [product name, string ID, GUID]
    products,
    // [service plan name, friendly name, GUIDs, indexes into products]
    plans: [...plans.values()].sort((a, b) => a.name.localeCompare(b.name, "en")).map((p) => [p.name, p.friendly, [...p.guids].sort(), [...p.products]]),
    skipped,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const local = process.argv[2];
  const markdown = local ? await readFile(local, "utf8") : await (await fetch(SOURCE_URL)).text();
  const data = parse(markdown);
  const { skipped, ...output } = data;
  const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "license-service-plans.json");
  await writeFile(target, JSON.stringify(output) + "\n");
  console.log(`Wrote ${output.products.length} products and ${output.plans.length} service plans to ${path.relative(process.cwd(), target)}. Skipped ${skipped} plan entries with unusable names.`);
}
