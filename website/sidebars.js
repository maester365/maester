import { existsSync } from "node:fs";

// docs/tests is generated from the test source by scripts/generate-test-docs.mjs. A build without PowerShell
// (Cloudflare Pages) skips the generator and uses the committed pages, which a bot pull request refreshes only
// after a change reaches main. So a suite added by the change being built has no pages there yet: list a suite
// only when its generated overview exists, so that build still passes.
function testSuite(suite, label) {
  if (!existsSync(new URL(`./docs/tests/${suite}/readme.md`, import.meta.url))) {
    console.warn(`[sidebars] No generated test docs for the '${suite}' suite yet; leaving it out of the sidebar.`);
    return [];
  }
  return [
    {
      type: "category",
      label,
      link: {type: 'doc', id: `tests/${suite}/overview`},
      collapsed: true,
      collapsible: true,
      items: [{ type: "autogenerated", dirName: `tests/${suite}` }]
    }
  ];
}

