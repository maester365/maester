export function featureIcon(product: string | null, feature: string | null): string | undefined {
  if (!product || !feature) return undefined
  const file = FEATURE_ICON[`${product}/${feature}`]
  return file ? `${ICON_BASE}/features/${file}.svg` : undefined
}
