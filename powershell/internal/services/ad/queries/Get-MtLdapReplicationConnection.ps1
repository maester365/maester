function Get-MtLdapReplicationConnection {
    [CmdletBinding()]
    [OutputType([object[]])]
    param(
        [Parameter(Mandatory)]
        [System.DirectoryServices.Protocols.LdapConnection] $Connection,

        [Parameter(Mandatory)]
        [string] $ConfigurationNamingContext
    )

    try {
        $attributes = @('distinguishedName', 'name', 'fromServer', 'transportType', 'options', 'enabledConnection')
        $entries = @(Invoke-MtLdapSearch -Connection $Connection -SearchBase "CN=Sites,$ConfigurationNamingContext" -Scope Subtree -Filter '(objectClass=nTDSConnection)' -Attributes $attributes)
        return @($entries | ForEach-Object {
            $optionsValue = if ($null -ne $_.options) { [int]$_.options } else { 0 }
            [PSCustomObject]@{
                Name = [string]$_.name
                DistinguishedName = [string]$_.DistinguishedName
                FromServer = [string]$_.fromServer
                TransportType = [string]$_.transportType
                Options = $_.options
                EnabledConnection = [bool]$_.enabledConnection
                Enabled = [bool]$_.enabledConnection
                AutoGenerated = [bool]($optionsValue -band 0x1)
            }
        })
    }
    catch {
        Write-Verbose "Could not query LDAP replication connections: $($_.Exception.Message)"
        return @()
    }
}
