function Test-MtCisAppPasswordsSystemGenerated {
    <#
    .SYNOPSIS
        Checks that the default app management policy blocks custom, user-chosen application passwords.

    .DESCRIPTION
        Checks that the default app management policy is enabled and that its custom password addition restriction is enabled and its restriction date is reached for both applications and service principals, so that new secrets are generated by Microsoft Entra ID.
        CIS Microsoft 365 Foundations Benchmark v7.0.0 (5.1.5.5, L1)

    .EXAMPLE
        Test-MtCisAppPasswordsSystemGenerated

        Returns true if the default app management policy blocks custom application passwords.

    .LINK
        https://maester.dev/docs/tests/CIS.M365.5.1.5.5
    #>
    [MaesterTest(
        Id = 'CIS.M365.5.1.5.5',
        Title = 'Ensure new application passwords are system-generated',
        Product = 'entra',
        Feature = 'applications',
        Area = 'applications',
        ResourceType = 'Tenant',
        Severity = 'Medium',
        UserImpact = 'Low',
        ImplementationCost = 'Medium',
        Mitre = ('T1110.001', 'T1110.003'),
        Control = ('cis-m365:5.1.5.5', 'nist-800-53-r5:IA-5'),
        Service = 'Graph',
        Author = 'JeremyFinney-lgtm'
    )]
    [CmdletBinding()]
    [OutputType([bool])]
    param()

    Write-Verbose 'Getting the default app management policy...'
    $appPolicy = Invoke-MtGraphRequest -RelativeUri 'policies/defaultAppManagementPolicy'

    $scopes = @(
        [pscustomobject]@{ Name = 'Applications'; Restrictions = @($appPolicy.applicationRestrictions.passwordCredentials) }
        [pscustomobject]@{ Name = 'Service principals'; Restrictions = @($appPolicy.servicePrincipalRestrictions.passwordCredentials) }
    )

    $report = foreach ($scope in $scopes) {
        $restriction = $scope.Restrictions | Where-Object { $_.restrictionType -eq 'customPasswordAddition' } | Select-Object -First 1
        $startDate = $restriction.restrictForAppsCreatedAfterDateTime
        $appliesNow = $null -eq $startDate -or ([datetime]$startDate).ToUniversalTime() -le [datetime]::UtcNow
        $checks = [ordered]@{
            'Default policy enabled' = $appPolicy.isEnabled -eq $true
            'Restriction enabled' = $restriction.state -eq 'enabled'
            'Restriction date reached' = [bool]$appliesNow
        }
        $failed = @($checks.GetEnumerator() | Where-Object { -not $_.Value } | ForEach-Object { $_.Key })
        [pscustomobject]@{
            Scope = $scope.Name
            State = if ($restriction.state) { $restriction.state } else { 'Not found' }
            Lifetime = ''
            Failed = $failed -join ', '
            Pass = $failed.Count -eq 0
        }
    }
    $testResult = @($report | Where-Object { -not $_.Pass }).Count -eq 0

    $passText = 'Custom application passwords are blocked, so new secrets are system-generated.'
    $failText = 'Custom application passwords are not blocked for applications and service principals.'

    $resultMd = "| Scope | Restriction state | Failed checks | Result |`n"
    $resultMd += "| --- | --- | --- | --- |`n"
    foreach ($row in $report) {
        $resultMd += "| $($row.Scope) | $($row.State) | $(if ($row.Failed) { $row.Failed } else { 'None' }) | $(if ($row.Pass) { '✅ Pass' } else { '❌ Fail' }) |`n"
    }

    if ($testResult) {
        $testResultMarkdown = "Well done. $passText`n`n%TestResult%"
    } else {
        $testResultMarkdown = "$failText`n`n%TestResult%"
    }
    $testResultMarkdown = $testResultMarkdown -replace '%TestResult%', $resultMd

    Add-MtTestResultDetail -Result $testResultMarkdown
    return $testResult
}
