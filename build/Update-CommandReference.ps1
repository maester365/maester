# Description: This script is used to generate the 'Command Reference' section of the Maester docusaurus site
# * This command needs to be run from the root of the project. e.g. ./build/Build-CommandReference.ps1
# * If running the docusaurus site locally you will need to stop and start Docusaurus to clear the 'Module not found' errors after running this command

# Alt3 2.x requires Microsoft.PowerShell.PlatyPS, whose YamlDotNet assembly conflicts with legacy PlatyPS.
$alt3DocusaurusVersion = "1.0.37"
$platyPSVersion = "0.14.2"

if (-not (Get-Module Alt3.Docusaurus.Powershell -ListAvailable | Where-Object { $_.Version -eq $alt3DocusaurusVersion })) { Install-Module Alt3.Docusaurus.Powershell -RequiredVersion $alt3DocusaurusVersion -Scope CurrentUser -Force -SkipPublisherCheck }
if (-not (Get-Module PlatyPS -ListAvailable | Where-Object { $_.Version -eq $platyPSVersion })) { Install-Module PlatyPS -RequiredVersion $platyPSVersion -Scope CurrentUser -Force -SkipPublisherCheck }
if (-not (Get-Module Pester -ListAvailable)) { Install-Module Pester -MinimumVersion 5.7.1 -MaximumVersion 5.7.1 -Scope CurrentUser -Force -SkipPublisherCheck }

Import-Module Alt3.Docusaurus.Powershell -RequiredVersion $alt3DocusaurusVersion
Import-Module PlatyPS -RequiredVersion $platyPSVersion
Import-Module Pester
Import-Module DnsClient

# Generate the command reference markdown
$commandsIndexFile = "./website/docs/commands/readme.md"
$readmeContent = Get-Content $commandsIndexFile  # Backup the readme.md since it will be deleted by New-DocusaurusHelp

# Exclude internal script filenames as well as any helper function names declared inside
# internal script files so multi-function files do not leak private helpers into docs.
$internalCommandFiles = Get-ChildItem @("./powershell/internal", "./powershell/internal/orca") -Filter *.ps1
$internalCommands = $internalCommandFiles | ForEach-Object { $_.BaseName }
$internalFunctionNames = foreach ($file in $internalCommandFiles) {
    foreach ($match in [regex]::Matches((Get-Content $file.FullName -Raw), '(?m)^\s*function\s+([A-Za-z0-9-]+)\s*\{')) {
        $match.Groups[1].Value
    }
}
$commandsToExclude = ($internalCommands + $internalFunctionNames) | Sort-Object -Unique

New-DocusaurusHelp -Module ./powershell/Maester.psm1 -DocsFolder ./website/docs -NoPlaceHolderExamples -EditUrl https://github.com/maester365/maester/blob/main/powershell/public/ -Exclude $commandsToExclude

# New-DocusaurusHelp only knows the flat -EditUrl root above, so every generated custom_edit_url
# assumes commands live directly under powershell/public/. Most commands actually live in nested
# category folders (e.g. powershell/public/maester/exchange/), which produces a dead "Edit this
# page" link. Rebuild custom_edit_url per command from the real file location instead.
$sourceScripts = Get-ChildItem -Path ./powershell/public, ./powershell/internal -Recurse -Filter *.ps1
$editUrlByCommand = @{}
foreach ($script in $sourceScripts) {
    $relativePath = (Resolve-Path -Relative $script.FullName) -replace '^\.[\\/]', '' -replace '\\', '/'
    $depth = ($relativePath -split '/').Count
    # Prefer the more deeply nested match when a function name collides across files.
    if (-not $editUrlByCommand.ContainsKey($script.BaseName) -or $depth -gt (($editUrlByCommand[$script.BaseName] -split '/').Count)) {
        $editUrlByCommand[$script.BaseName] = $relativePath
    }
}
# Helper functions defined inside a multi-function file don't share the file's base name,
# so fall back to a content search for those.
$multiFunctionCandidates = Get-ChildItem ./website/docs/commands -Filter *.mdx | Where-Object { -not $editUrlByCommand.ContainsKey($_.BaseName) }
foreach ($candidate in $multiFunctionCandidates) {
    $match = $sourceScripts | Where-Object { (Get-Content $_.FullName -Raw) -match "(?im)^\s*function\s+$($candidate.BaseName)\s*\{" } | Select-Object -First 1
    if ($match) {
        $editUrlByCommand[$candidate.BaseName] = (Resolve-Path -Relative $match.FullName) -replace '^\.[\\/]', '' -replace '\\', '/'
    }
}

$generatedParameterDescriptions = @{
    ProgressAction = "Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider, such as the progress bars generated by Write-Progress."
}

$cmdMarkdownFiles = Get-ChildItem ./website/docs/commands -Filter *.mdx
$versionedCmdMarkdownFiles = if (Test-Path ./website/versioned_docs) {
    Get-ChildItem ./website/versioned_docs -Directory | ForEach-Object {
        $commandsDirectory = Join-Path $_.FullName "commands"
        if (Test-Path $commandsDirectory) {
            Get-ChildItem $commandsDirectory -Filter *.mdx
        }
    }
}
$allCmdMarkdownFiles = @($cmdMarkdownFiles) + @($versionedCmdMarkdownFiles)
foreach ($file in $allCmdMarkdownFiles) {
    if ($editUrlByCommand.ContainsKey($file.BaseName)) {
        $correctEditUrl = "https://github.com/maester365/maester/blob/main/$($editUrlByCommand[$file.BaseName])"
        $content = Get-Content $file.FullName -Raw
        $content = $content -replace '(?m)^custom_edit_url:\s*.+$', "custom_edit_url: $correctEditUrl"
        Set-Content -Path $file.FullName -Value $content -NoNewline
    }
}
foreach ($file in $cmdMarkdownFiles) {
    $content = Get-Content $file.FullName -Raw
    foreach ($parameterName in $generatedParameterDescriptions.Keys) {
        $description = $generatedParameterDescriptions[$parameterName]
        $content = $content.Replace("\{\{ Fill $parameterName Description \}\}", $description)
        $content = $content.Replace("{{ Fill $parameterName Description }}", $description)
    }
    Set-Content $file.FullName $content -NoNewline
}

# Update the markdown to include the synopsis as description so it can be displayed correctly in the doc links.
foreach ($file in $cmdMarkdownFiles) {
    $content = Get-Content $file
    $synopsis = $content[($content.IndexOf("## SYNOPSIS") + 2)] # Get the synopsis
    if (![string]::IsNullOrWhiteSpace($synopsis)) {
        # Escape embedded double quotes and wrap value in double quotes so YAML front matter
        # remains valid even when the synopsis contains characters like ':' that have YAML meaning.
        $escapedSynopsis = $synopsis -replace '"', '\"'
        $updatedContent = $content.Replace("id:", "sidebar_class_name: hidden`ndescription: `"$escapedSynopsis`"`nid:")
        Set-Content $file $updatedContent
    }
}

Set-Content $commandsIndexFile $readmeContent  # Restore the readme content

# Sync generated command files to all versioned doc folders
$versionedDocsRoot = "./website/versioned_docs"
if (Test-Path $versionedDocsRoot) {
    $sourceCommands = "./website/docs/commands"
    $versionFolders = Get-ChildItem $versionedDocsRoot -Directory
    foreach ($versionFolder in $versionFolders) {
        $targetCommands = Join-Path $versionFolder.FullName "commands"
        if (Test-Path $targetCommands) {
            $sourceFiles = Get-ChildItem $sourceCommands -Filter *.mdx
            $sourceNames = $sourceFiles.Name

            Get-ChildItem $targetCommands -Filter *.mdx | Where-Object { $_.Name -notin $sourceNames } | Remove-Item -Force

            foreach ($sourceFile in $sourceFiles) {
                $targetFile = Join-Path $targetCommands $sourceFile.Name
                if (-not (Test-Path $targetFile)) {
                    Copy-Item $sourceFile.FullName $targetFile
                    Write-Verbose "Copied $($sourceFile.Name) to $($versionFolder.Name)"
                }
            }
        }
    }
}
