<#
.SYNOPSIS
Writes the Microsoft Zero Trust Workshop plan that the Zero Trust Assessment pack shows in the Maester report.

.DESCRIPTION
Downloads the Zero Trust Workshop (https://zerotrust.microsoft.com) and writes it into the pack's workshop folder,
one file per pillar, plus the icons the plan uses:

- the pillars' functional areas and tasks from https://zerotrust.microsoft.com/data/<pillar>-pillar-data.json,
  without the tasks the workshop hides;
- each task's guidance from src/react/docs/workshop-guidance in microsoft/zerotrustassessment (MIT licence),
  without its front matter, embedded videos, title and the effort and impact lines the plan shows anyway;
- the assessment tests that measure each task, from src/powershell/assets/ztw-task-mapping.json in the same
  repository (MIT licence), as ZTA.<test id>;
- every icon a task or area names, from https://zerotrust.microsoft.com/icons/<name>, as SVG text.

The files are generated: do not edit them. Maester's own additions (its tests for a task, notes and extra tasks)
are kept by hand in workshop/maester.json, which this script does not touch. A pillar file keeps its Updated date
when nothing else in it changed, so a rerun on unchanged sources leaves no diff.

.PARAMETER OutputPath
The folder to write. Defaults to packs/zero-trust-assessment/workshop in this repository.

.PARAMETER Branch
The branch of microsoft/zerotrustassessment to read the guidance and the mapping from. Defaults to main.

.EXAMPLE
./build/zero-trust-workshop/Update-MtZtWorkshopData.ps1
#>
[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingWriteHost', '', Justification = 'Build script that reports progress to the console.')]
[CmdletBinding()]
param(
    [string] $OutputPath = (Join-Path -Path $PSScriptRoot -ChildPath '..' -AdditionalChildPath '..', 'packs', 'zero-trust-assessment', 'workshop'),

    [string] $Branch = 'main'
)

$ErrorActionPreference = 'Stop'

$site = 'https://zerotrust.microsoft.com'
$repository = 'microsoft/zerotrustassessment'
$rawRoot = "https://raw.githubusercontent.com/$repository/$Branch"
$guidanceRoot = 'src/react/docs/workshop-guidance/'
$comment = 'Generated by build/zero-trust-workshop/Update-MtZtWorkshopData.ps1. Do not edit.'

# Pillar ID and name in Maester, the workshop's data file, and the key of the pillar in Microsoft's mapping.
$pillars = @(
    [pscustomobject]@{ Id = 'identity'; Name = 'Identity'; File = 'identity-pillar-data.json'; MappingKey = 'identity' }
    [pscustomobject]@{ Id = 'devices'; Name = 'Devices'; File = 'devices-pillar-data.json'; MappingKey = 'devices' }
    [pscustomobject]@{ Id = 'data'; Name = 'Data'; File = 'data-pillar-data.json'; MappingKey = 'data' }
    [pscustomobject]@{ Id = 'network'; Name = 'Network'; File = 'network-pillar-data.json'; MappingKey = 'network' }
    [pscustomobject]@{ Id = 'infrastructure'; Name = 'Infrastructure'; File = 'infrastructure-pillar-data.json'; MappingKey = 'infrastructure' }
    [pscustomobject]@{ Id = 'security-operations'; Name = 'Security Operations'; File = 'security-ops-pillar-data.json'; MappingKey = 'secops' }
    [pscustomobject]@{ Id = 'ai'; Name = 'AI'; File = 'ai-pillar-data.json'; MappingKey = 'ai' }
)

function Invoke-MtZtwDownload {
    # Returns the text at a URL, or $null on 404. Retries other failures three times.
    param([Parameter(Mandatory)] [string] $Uri)
    $headers = @{ 'User-Agent' = 'maester-build' }
    if ($Uri -like 'https://api.github.com/*' -and $env:GITHUB_TOKEN) { $headers.Authorization = "Bearer $env:GITHUB_TOKEN" }
    for ($attempt = 1; ; $attempt++) {
        try {
            $response = Invoke-WebRequest -Uri $Uri -Headers $headers -UseBasicParsing -ErrorAction Stop
            $content = $response.Content
            if ($content -is [byte[]]) { $content = [System.Text.Encoding]::UTF8.GetString($content) }
            return ([string]$content).TrimStart([char]0xFEFF)
        } catch {
            $status = $null
            if ($_.Exception.PSObject.Properties['Response'] -and $_.Exception.Response) { $status = [int]$_.Exception.Response.StatusCode }
            if ($status -eq 404) { return $null }
            if ($attempt -ge 4) { throw "Could not download ${Uri}: $($_.Exception.Message)" }
            Start-Sleep -Seconds ([math]::Pow(2, $attempt))
        }
    }
}

function ConvertTo-MtZtwText {
    # Collapses whitespace in a name or label.
    param([AllowNull()] $Value)
    if ($null -eq $Value) { return $null }
    $text = ([string]$Value -replace '\s+', ' ').Trim()
    if ($text) { $text } else { $null }
}

function ConvertTo-MtZtwGuidance {
    # Cleans a workshop guidance document for the report.
    param([Parameter(Mandatory)] [string] $Markdown)
    $text = $Markdown -replace "`r`n?", "`n"
    # YAML front matter.
    $text = $text -replace '^\s*---\n[\s\S]*?\n---[ \t]*\n', ''
    # Embedded videos.
    $text = $text -replace '(?is)<iframe\b.*?(</iframe\s*>|/>)', ''
    # The title (the plan shows the task's name) and the effort and impact lines (the plan shows those too).
    $text = ([regex]'(?m)^[ \t]*#[ \t]+[^\n]*\n?').Replace($text, '', 1)
    $text = $text -replace '(?im)^[ \t]*(?:>[ \t]*)?\*\*(?:Implementation Effort|User Impact)\b[^\n]*\n?', ''
    # A quote block left with nothing in it.
    $text = $text -replace '(?m)^[ \t]*>[ \t]*\n(?=[ \t]*(?:>[ \t]*)?\n|\z)', ''
    $text = ($text -replace '(?m)[ \t]+$', '') -replace '\n{3,}', "`n`n"
    $text = $text.Trim()
    if ($text) { $text } else { $null }
}

function ConvertTo-MtZtwSvg {
    # SVG text without its XML prolog and comments.
    param([Parameter(Mandatory)] [string] $Svg)
    $text = $Svg -replace "`r`n?", "`n"
    $text = $text -replace '<\?xml[^>]*\?>', ''
    $text = $text -replace '<!--[\s\S]*?-->', ''
    $text = $text -replace '<!DOCTYPE[^>]*>', ''
    $text = ($text -replace '(?m)^[ \t]*\n', '').Trim()
    $text
}

function Write-MtZtwFile {
    # Writes JSON with LF line endings, UTF-8 without BOM. Returns $true when the file changed.
    param([Parameter(Mandatory)] [string] $Path, [Parameter(Mandatory)] $Object)
    $json = ($Object | ConvertTo-Json -Depth 10) -replace "`r`n", "`n"
    $json += "`n"
    if ((Test-Path -LiteralPath $Path) -and ([System.IO.File]::ReadAllText($Path) -ceq $json)) { return $false }
    [System.IO.File]::WriteAllText($Path, $json, [System.Text.UTF8Encoding]::new($false))
    $true
}

$null = New-Item -ItemType Directory -Path $OutputPath -Force
$OutputPath = (Resolve-Path -LiteralPath $OutputPath).ProviderPath

# Microsoft's mapping of assessment tests to workshop tasks, inverted: task ID -> test IDs.
Write-Host 'Reading the assessment-to-task mapping.'
$mappingText = Invoke-MtZtwDownload -Uri "$rawRoot/src/powershell/assets/ztw-task-mapping.json"
if (-not $mappingText) { throw "The mapping src/powershell/assets/ztw-task-mapping.json was not found in $repository." }
$mapping = $mappingText | ConvertFrom-Json -AsHashtable
$checksByTask = @{}
foreach ($pillarKey in $mapping.Keys) {
    foreach ($testId in $mapping[$pillarKey].Keys) {
        foreach ($taskId in @($mapping[$pillarKey][$testId])) {
            if (-not $checksByTask.ContainsKey($taskId)) { $checksByTask[$taskId] = [System.Collections.Generic.HashSet[string]]::new() }
            $null = $checksByTask[$taskId].Add([string]$testId)
        }
    }
}
$sortTestId = { $n = 0; if ([int]::TryParse($_, [ref]$n)) { '{0:D10}' -f $n } else { $_ } }

# The guidance documents, by task ID, from one listing of the repository.
Write-Host 'Listing the workshop guidance.'
$tree = (Invoke-MtZtwDownload -Uri "https://api.github.com/repos/$repository/git/trees/${Branch}?recursive=1") | ConvertFrom-Json
if ($tree.truncated) { Write-Warning 'The repository listing is truncated; some guidance may be missing.' }
$guidancePaths = @{}
foreach ($entry in $tree.tree) {
    if ($entry.type -ne 'blob' -or -not $entry.path.StartsWith($guidanceRoot) -or -not $entry.path.EndsWith('.md')) { continue }
    $taskId = [System.IO.Path]::GetFileNameWithoutExtension($entry.path)
    if (-not $guidancePaths.ContainsKey($taskId)) { $guidancePaths[$taskId] = [System.Collections.Generic.List[string]]::new() }
    $guidancePaths[$taskId].Add($entry.path)
}

$icons = [System.Collections.Generic.SortedSet[string]]::new([System.StringComparer]::Ordinal)
$knownTasks = [System.Collections.Generic.HashSet[string]]::new()
$updated = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd')
$summary = foreach ($pillar in $pillars) {
    Write-Host "Reading the $($pillar.Name) pillar."
    $data = (Invoke-MtZtwDownload -Uri "$site/data/$($pillar.File)") | ConvertFrom-Json -Depth 10
    if (-not $data) { throw "$site/data/$($pillar.File) was not found." }

    $areas = @(foreach ($area in $data.functionalAreas) {
            $row = [ordered]@{ Id = [string]$area.id; Name = ConvertTo-MtZtwText $area.name; Description = ConvertTo-MtZtwText $area.description; Icon = ConvertTo-MtZtwText $area.icon }
            foreach ($key in @($row.Keys)) { if ($null -eq $row[$key]) { $row.Remove($key) } }
            if ($row.Icon) { $null = $icons.Add($row.Icon) }
            [pscustomobject]$row
        })

    $tasks = @(foreach ($task in $data.tasks) {
            if ($task.PSObject.Properties['isHidden'] -and $task.isHidden) { continue }
            if ([string]$task.status -eq 'hidden') { continue }
            $id = [string]$task.id
            $null = $knownTasks.Add($id)

            # The guidance the task's link names (task NET-007 links to network/NET_001), otherwise, for a task
            # that links elsewhere, the document named after the task.
            $doc = $null
            $path = $null
            $linkMatch = [regex]::Match([string]$task.link, '/workshop-guidance/(?<folder>[^/]+)/(?<name>[^/?#]+?)/?(?:[?#].*)?$')
            if ($linkMatch.Success) {
                $wanted = "$guidanceRoot$($linkMatch.Groups['folder'].Value)/$($linkMatch.Groups['name'].Value).md"
                $path = @($guidancePaths[$linkMatch.Groups['name'].Value]) | Where-Object { $_ -and $_ -eq $wanted } | Select-Object -First 1
                if (-not $path) { $path = @($guidancePaths[$linkMatch.Groups['name'].Value]) | Where-Object { $_ -and $_.ToLowerInvariant() -eq $wanted.ToLowerInvariant() } | Select-Object -First 1 }
            } else {
                $path = @($guidancePaths[$id]) + @($guidancePaths[$id.Replace('-', '_')]) | Where-Object { $_ } | Sort-Object | Select-Object -First 1
            }
            if ($path) {
                $markdown = Invoke-MtZtwDownload -Uri "$rawRoot/$path"
                if ($markdown) { $doc = ConvertTo-MtZtwGuidance -Markdown $markdown }
            }

            $checks = @()
            if ($checksByTask.ContainsKey($id)) { $checks = @($checksByTask[$id] | Sort-Object $sortTestId | ForEach-Object { "ZTA.$_" }) }

            $row = [ordered]@{
                Id           = $id
                Name         = ConvertTo-MtZtwText $task.name
                AreaId       = ConvertTo-MtZtwText $task.functionalAreaId
                Swimlane     = ConvertTo-MtZtwText $task.swimlane
                Phase        = ConvertTo-MtZtwText $task.phase
                Priority     = ConvertTo-MtZtwText $task.priority
                Effort       = ConvertTo-MtZtwText $task.implementationEffort
                UserImpact   = ConvertTo-MtZtwText $task.userImpact
                License      = ConvertTo-MtZtwText $task.license
                Cisa         = ConvertTo-MtZtwText $task.CISAMaturityStage
                Dependencies = @($task.dependencies | Where-Object { $_ } | ForEach-Object { [string]$_ })
                Icon         = ConvertTo-MtZtwText $task.icon
                Link         = ConvertTo-MtZtwText $task.link
                Doc          = $doc
                Checks       = $checks
            }
            foreach ($key in @($row.Keys)) { if ($null -eq $row[$key]) { $row.Remove($key) } }
            if ($row.Icon) { $null = $icons.Add($row.Icon) }
            [pscustomobject]$row
        })

    $file = Join-Path $OutputPath "$($pillar.Id).json"
    $build = {
        param($date)
        [ordered]@{
            '$comment' = $comment
            Id         = $pillar.Id
            Name       = $pillar.Name
            Source     = [ordered]@{ Url = $site; Docs = "https://github.com/$repository"; Updated = $date }
            Areas      = $areas
            Tasks      = $tasks
        }
    }
    # Keep the previous date when nothing else changed.
    $previousDate = $null
    if (Test-Path -LiteralPath $file) {
        $match = [regex]::Match([System.IO.File]::ReadAllText($file), '"Updated":\s*"(\d{4}-\d{2}-\d{2})"')
        if ($match.Success) { $previousDate = $match.Groups[1].Value }
    }
    $changed = $true
    if ($previousDate) { $changed = Write-MtZtwFile -Path $file -Object (& $build $previousDate) }
    if ($changed) { $null = Write-MtZtwFile -Path $file -Object (& $build $updated) }

    [pscustomobject]@{
        Pillar   = $pillar.Id
        Tasks    = $tasks.Count
        WithDoc  = @($tasks | Where-Object { $_.PSObject.Properties['Doc'] }).Count
        Checked  = @($tasks | Where-Object { $_.Checks.Count -gt 0 }).Count
        Changed  = $changed
        SizeKB   = [math]::Round((Get-Item -LiteralPath $file).Length / 1KB, 1)
    }
}

foreach ($taskId in $checksByTask.Keys | Sort-Object) {
    if (-not $knownTasks.Contains($taskId)) { Write-Warning "The mapping names task $taskId, which no pillar shows." }
}

Write-Host "Downloading $($icons.Count) icons."
$iconMap = [ordered]@{}
foreach ($name in $icons) {
    $svg = Invoke-MtZtwDownload -Uri "$site/icons/$([uri]::EscapeDataString($name))"
    if (-not $svg) { Write-Warning "The icon $name was not found."; continue }
    $iconMap[$name] = ConvertTo-MtZtwSvg -Svg $svg
}
$iconFile = Join-Path $OutputPath 'icons.json'
$null = Write-MtZtwFile -Path $iconFile -Object ([ordered]@{ '$comment' = $comment; Icons = $iconMap })

$summary | Format-Table -AutoSize | Out-String | Write-Host
Write-Host ("icons.json: {0} icons, {1:N1} KB" -f $iconMap.Count, ((Get-Item -LiteralPath $iconFile).Length / 1KB))
