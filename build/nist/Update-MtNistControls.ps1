<#
.SYNOPSIS
    Refreshes the pinned list of NIST SP 800-53 Rev. 5 controls (powershell/assets/MaesterNistControls.json).

.DESCRIPTION
    A test can say which NIST SP 800-53 controls it supports: Control = 'nist-800-53-r5:IA-2(1)'. The unit tests
    check those references against this list, and the test builder on maester.dev uses it for its lookup. The
    list is read from the OSCAL catalog NIST publishes. Withdrawn controls are left out.

.EXAMPLE
    ./build/nist/Update-MtNistControls.ps1
#>
[CmdletBinding()]
param(
    [string] $CatalogUrl = 'https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog-min.json',

    # A local copy of the catalog, used instead of downloading.
    [string] $CatalogPath,

    [string] $OutputPath = "$PSScriptRoot/../../powershell/assets/MaesterNistControls.json"
)

$ErrorActionPreference = 'Stop'
$json = if ($CatalogPath) { Get-Content -LiteralPath $CatalogPath -Raw } else { (Invoke-WebRequest -Uri $CatalogUrl).Content }
$catalog = ($json | ConvertFrom-Json -Depth 64).catalog

$controls = [System.Collections.Generic.List[object]]::new()
function Add-Control {
    param($Control, [string] $Family, [string] $ParentTitle)
    $withdrawn = @($Control.props | Where-Object { $_.name -eq 'status' -and $_.value -eq 'withdrawn' }).Count -gt 0
    # The label without a class is the form people write: AC-2, IA-2(1).
    $label = @($Control.props | Where-Object { $_.name -eq 'label' -and -not $_.PSObject.Properties['class'] })[0].value
    $title = if ($ParentTitle) { "$ParentTitle | $($Control.title)" } else { [string]$Control.title }
    if (-not $withdrawn -and $label) { $controls.Add([ordered]@{ Id = $label; Title = $title; Family = $Family }) }
    foreach ($enhancement in @($Control.controls)) { if ($enhancement) { Add-Control -Control $enhancement -Family $Family -ParentTitle ([string]$Control.title) } }
}
foreach ($group in $catalog.groups) { foreach ($control in $group.controls) { Add-Control -Control $control -Family $group.title } }
if ($controls.Count -lt 900) { throw "Only $($controls.Count) controls were read. The catalog layout may have changed." }

$data = [ordered]@{
    Framework = 'nist-800-53-r5'
    Name      = 'NIST SP 800-53 Rev. 5'
    Version   = [string]$catalog.metadata.version
    Source    = $CatalogUrl
    Note      = 'Generated by build/nist/Update-MtNistControls.ps1. Do not edit. NIST publications are in the public domain.'
    Controls  = $controls
}
$text = ($data | ConvertTo-Json -Depth 6) -replace "`r`n", "`n"
[System.IO.File]::WriteAllText($OutputPath, $text + "`n", [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $($controls.Count) controls (version $($data.Version)) to $OutputPath"
